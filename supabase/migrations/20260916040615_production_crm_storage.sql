-- Journey Expert Ltd. production CRM/storage hardening
-- Idempotent migration. Do not hard-code staff user IDs or service-role secrets.

begin;

create table if not exists public.staff_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  role text not null default 'counsellor',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.staff_profiles add column if not exists email text;
alter table public.staff_profiles add column if not exists full_name text;
alter table public.staff_profiles add column if not exists role text not null default 'counsellor';
alter table public.staff_profiles add column if not exists is_active boolean not null default true;
alter table public.staff_profiles add column if not exists created_at timestamptz not null default now();
alter table public.staff_profiles add column if not exists updated_at timestamptz not null default now();

create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text,
  email text,
  phone text,
  source text not null default 'website',
  status text not null default 'New',
  preferred_country text,
  education_level text,
  message text,
  assigned_to uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

alter table public.leads add column if not exists name text;
alter table public.leads add column if not exists email text;
alter table public.leads add column if not exists phone text;
alter table public.leads add column if not exists source text not null default 'website';
alter table public.leads add column if not exists status text not null default 'New';
alter table public.leads add column if not exists preferred_country text;
alter table public.leads add column if not exists education_level text;
alter table public.leads add column if not exists message text;
alter table public.leads add column if not exists assigned_to uuid references auth.users(id) on delete set null;
alter table public.leads add column if not exists updated_at timestamptz not null default now();

create or replace function public.is_jel_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.staff_profiles sp
    where sp.id = auth.uid()
      and sp.is_active = true
      and lower(sp.role) in ('super_admin','admin','counsellor','counselor','visa_officer','accounts','reception')
  );
$$;

create or replace function public.is_jel_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.staff_profiles sp
    where sp.id = auth.uid()
      and sp.is_active = true
      and lower(sp.role) in ('super_admin','admin')
  );
$$;

revoke all on function public.is_jel_staff() from public;
revoke all on function public.is_jel_admin() from public;
grant execute on function public.is_jel_staff() to authenticated;
grant execute on function public.is_jel_admin() to authenticated;

alter table public.staff_profiles enable row level security;
alter table public.leads enable row level security;

-- Recreate only JEL-owned policy names; unrelated custom policies are not touched.
drop policy if exists "staff_profiles_self_read" on public.staff_profiles;
drop policy if exists "staff_profiles_admin_manage" on public.staff_profiles;
create policy "staff_profiles_self_read"
on public.staff_profiles for select
to authenticated
using (id = auth.uid() or public.is_jel_admin());
create policy "staff_profiles_admin_manage"
on public.staff_profiles for all
to authenticated
using (public.is_jel_admin())
with check (public.is_jel_admin());

drop policy if exists "leads_staff_read" on public.leads;
drop policy if exists "leads_staff_update" on public.leads;
drop policy if exists "leads_admin_delete" on public.leads;
create policy "leads_staff_read"
on public.leads for select
to authenticated
using (public.is_jel_staff());
create policy "leads_staff_update"
on public.leads for update
to authenticated
using (public.is_jel_staff())
with check (public.is_jel_staff());
create policy "leads_admin_delete"
on public.leads for delete
to authenticated
using (public.is_jel_admin());

-- Public lead creation is exposed only through a constrained RPC. Anonymous users
-- receive no direct table privileges, which prevents arbitrary column injection.
revoke all on table public.leads from anon;
grant select, insert, update, delete on table public.leads to authenticated;

create or replace function public.submit_public_lead(
  p_name text,
  p_email text,
  p_phone text,
  p_preferred_country text,
  p_education_level text,
  p_message text,
  p_source text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
  v_name text := left(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g'), 120);
  v_email text := nullif(left(lower(trim(coalesce(p_email, ''))), 180), '');
  v_phone text := left(regexp_replace(coalesce(p_phone, ''), '\s+', ' ', 'g'), 40);
  v_source text := lower(trim(coalesce(p_source, 'website')));
begin
  v_name := trim(v_name);
  v_phone := trim(v_phone);

  if v_name = '' or v_phone = '' then
    raise exception 'name_and_phone_required' using errcode = '22023';
  end if;

  if v_email is not null and v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'invalid_email' using errcode = '22023';
  end if;

  if v_source not in ('website','website_exit','consultation','student_portal','angela') then
    v_source := 'website';
  end if;

  insert into public.leads (
    name, email, phone, source, status, preferred_country, education_level, message
  ) values (
    v_name,
    v_email,
    v_phone,
    v_source,
    'New',
    nullif(left(trim(coalesce(p_preferred_country, '')), 100), ''),
    nullif(left(trim(coalesce(p_education_level, '')), 100), ''),
    nullif(left(trim(coalesce(p_message, '')), 1200), '')
  ) returning id into v_id;

  return v_id;
end;
$$;

revoke all on function public.submit_public_lead(text,text,text,text,text,text,text) from public;
grant execute on function public.submit_public_lead(text,text,text,text,text,text,text) to anon, authenticated;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists leads_touch_updated_at on public.leads;
create trigger leads_touch_updated_at
before update on public.leads
for each row execute function public.touch_updated_at();

drop trigger if exists staff_profiles_touch_updated_at on public.staff_profiles;
create trigger staff_profiles_touch_updated_at
before update on public.staff_profiles
for each row execute function public.touch_updated_at();

-- Sensitive student documents must remain private. Object names follow:
-- <auth-user-uuid>/<filename>. Staff can access all objects; students only their own folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'student-documents',
  'student-documents',
  false,
  10485760,
  array[
    'application/pdf',
    'image/jpeg',
    'image/png',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
  ]
)
on conflict (id) do update set
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "student_documents_owner_read" on storage.objects;
drop policy if exists "student_documents_owner_insert" on storage.objects;
drop policy if exists "student_documents_owner_update" on storage.objects;
drop policy if exists "student_documents_owner_delete" on storage.objects;
drop policy if exists "student_documents_staff_all" on storage.objects;

create policy "student_documents_owner_read"
on storage.objects for select
to authenticated
using (
  bucket_id = 'student-documents'
  and (storage.foldername(name))[1] = auth.uid()::text
);
create policy "student_documents_owner_insert"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'student-documents'
  and (storage.foldername(name))[1] = auth.uid()::text
);
create policy "student_documents_owner_update"
on storage.objects for update
to authenticated
using (
  bucket_id = 'student-documents'
  and (storage.foldername(name))[1] = auth.uid()::text
)
with check (
  bucket_id = 'student-documents'
  and (storage.foldername(name))[1] = auth.uid()::text
);
create policy "student_documents_owner_delete"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'student-documents'
  and (storage.foldername(name))[1] = auth.uid()::text
);
create policy "student_documents_staff_all"
on storage.objects for all
to authenticated
using (bucket_id = 'student-documents' and public.is_jel_staff())
with check (bucket_id = 'student-documents' and public.is_jel_staff());

commit;
