-- JEL authenticated student profiles and application tracking
-- Safe to apply after 20260916_production_crm_storage.sql.

begin;

create sequence if not exists public.student_id_seq start 1;

create or replace function public.generate_student_id()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  next_value bigint;
begin
  next_value := nextval('public.student_id_seq');
  return 'JEL-' || extract(year from now())::int::text || '-' || lpad(next_value::text, 5, '0');
end;
$$;

create table if not exists public.students (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid unique references auth.users(id) on delete cascade,
  student_id text unique not null default public.generate_student_id(),
  full_name text,
  email text,
  phone text,
  preferred_country text,
  education_level text,
  gpa text,
  english_test text,
  english_score text,
  status text not null default 'New Lead',
  assigned_to uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.applications (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students(id) on delete cascade,
  target_country text,
  target_university text,
  target_course text,
  intake text,
  current_stage text not null default 'New Lead',
  status text not null default 'Active',
  counselor_notes text,
  assigned_to uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.documents (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students(id) on delete cascade,
  application_id uuid references public.applications(id) on delete set null,
  storage_path text not null,
  file_name text not null,
  mime_type text,
  size_bytes bigint,
  category text,
  status text not null default 'Uploaded',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(student_id, storage_path)
);

create table if not exists public.follow_ups (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students(id) on delete cascade,
  application_id uuid references public.applications(id) on delete cascade,
  assigned_to uuid references auth.users(id) on delete set null,
  due_at timestamptz,
  status text not null default 'Open',
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  student_id uuid references public.students(id) on delete cascade,
  action text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.students enable row level security;
alter table public.applications enable row level security;
alter table public.documents enable row level security;
alter table public.follow_ups enable row level security;
alter table public.activity_logs enable row level security;

create or replace function public.current_student_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select s.id from public.students s where s.auth_user_id = auth.uid() limit 1;
$$;
revoke all on function public.current_student_id() from public;
grant execute on function public.current_student_id() to authenticated;

-- Student profiles: owner can read/update only their own profile; staff can manage all.
drop policy if exists "students_self_read" on public.students;
drop policy if exists "students_self_update" on public.students;
drop policy if exists "students_staff_manage" on public.students;
create policy "students_self_read" on public.students for select to authenticated using (auth_user_id = auth.uid() or public.is_jel_staff());
create policy "students_self_update" on public.students for update to authenticated using (auth_user_id = auth.uid()) with check (auth_user_id = auth.uid());
create policy "students_staff_manage" on public.students for all to authenticated using (public.is_jel_staff()) with check (public.is_jel_staff());

-- Applications: students can read only their own; staff can create/update/delete.
drop policy if exists "applications_student_read" on public.applications;
drop policy if exists "applications_staff_manage" on public.applications;
create policy "applications_student_read" on public.applications for select to authenticated using (student_id = public.current_student_id() or public.is_jel_staff());
create policy "applications_staff_manage" on public.applications for all to authenticated using (public.is_jel_staff()) with check (public.is_jel_staff());

-- Document metadata mirrors private storage ownership.
drop policy if exists "documents_student_read" on public.documents;
drop policy if exists "documents_staff_manage" on public.documents;
create policy "documents_student_read" on public.documents for select to authenticated using (student_id = public.current_student_id() or public.is_jel_staff());
create policy "documents_staff_manage" on public.documents for all to authenticated using (public.is_jel_staff()) with check (public.is_jel_staff());

-- Follow-ups and activity logs are staff-only CRM data.
drop policy if exists "follow_ups_staff_manage" on public.follow_ups;
drop policy if exists "activity_logs_staff_read" on public.activity_logs;
drop policy if exists "activity_logs_staff_insert" on public.activity_logs;
create policy "follow_ups_staff_manage" on public.follow_ups for all to authenticated using (public.is_jel_staff()) with check (public.is_jel_staff());
create policy "activity_logs_staff_read" on public.activity_logs for select to authenticated using (public.is_jel_staff());
create policy "activity_logs_staff_insert" on public.activity_logs for insert to authenticated with check (public.is_jel_staff());

grant select, update on public.students to authenticated;
grant select on public.applications, public.documents to authenticated;
grant select, insert, update, delete on public.applications, public.documents, public.follow_ups to authenticated;
grant select, insert on public.activity_logs to authenticated;

-- Create/synchronize a student row when a student registers through Supabase Auth.
create or replace function public.sync_student_from_auth()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if lower(coalesce(new.raw_user_meta_data->>'role', '')) = 'student' then
    insert into public.students (
      auth_user_id, full_name, email, phone, preferred_country, education_level, gpa, english_test, english_score
    ) values (
      new.id,
      nullif(trim(coalesce(new.raw_user_meta_data->>'fullName', '')), ''),
      new.email,
      nullif(trim(coalesce(new.raw_user_meta_data->>'mobileNumber', '')), ''),
      nullif(trim(coalesce(new.raw_user_meta_data->>'preferredCountry', '')), ''),
      nullif(trim(coalesce(new.raw_user_meta_data->>'educationLevel', '')), ''),
      nullif(trim(coalesce(new.raw_user_meta_data->>'gpa', '')), ''),
      nullif(trim(coalesce(new.raw_user_meta_data->>'englishTest', '')), ''),
      nullif(trim(coalesce(new.raw_user_meta_data->>'englishScore', '')), '')
    ) on conflict (auth_user_id) do update set
      full_name = excluded.full_name,
      email = excluded.email,
      phone = excluded.phone,
      preferred_country = excluded.preferred_country,
      education_level = excluded.education_level,
      gpa = excluded.gpa,
      english_test = excluded.english_test,
      english_score = excluded.english_score,
      updated_at = now();
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_student_created on auth.users;
create trigger on_auth_student_created
after insert or update of raw_user_meta_data, email on auth.users
for each row execute function public.sync_student_from_auth();

-- Backfill existing Auth users that were created by the production student portal.
insert into public.students (
  auth_user_id, full_name, email, phone, preferred_country, education_level, gpa, english_test, english_score
)
select
  u.id,
  nullif(trim(coalesce(u.raw_user_meta_data->>'fullName', '')), ''),
  u.email,
  nullif(trim(coalesce(u.raw_user_meta_data->>'mobileNumber', '')), ''),
  nullif(trim(coalesce(u.raw_user_meta_data->>'preferredCountry', '')), ''),
  nullif(trim(coalesce(u.raw_user_meta_data->>'educationLevel', '')), ''),
  nullif(trim(coalesce(u.raw_user_meta_data->>'gpa', '')), ''),
  nullif(trim(coalesce(u.raw_user_meta_data->>'englishTest', '')), ''),
  nullif(trim(coalesce(u.raw_user_meta_data->>'englishScore', '')), '')
from auth.users u
where lower(coalesce(u.raw_user_meta_data->>'role', '')) = 'student'
on conflict (auth_user_id) do nothing;

create index if not exists applications_student_id_idx on public.applications(student_id);
create index if not exists documents_student_id_idx on public.documents(student_id);
create index if not exists follow_ups_due_at_idx on public.follow_ups(due_at) where status <> 'Closed';
create index if not exists students_assigned_to_idx on public.students(assigned_to);

commit;
